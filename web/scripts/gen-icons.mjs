// Codegen: turn the Material Symbols Rounded SVGs we actually use into one small
// TypeScript module of path data.
//
// Why codegen and not the icon font the design links: the app's CSP pins
// `font-src 'self' data:` and `style-src 'self' 'unsafe-inline'`, so
// fonts.googleapis.com is refused outright (server/src/lib/csp.ts, and
// server/test/csp.test.ts guards it). Self-hosting the font instead would ship a
// multi-megabyte woff2 to every visitor for ~60 glyphs. This emits only the glyphs
// named below, so @material-symbols/svg-300 stays a devDependency and nothing extra
// reaches the browser.
//
// Weight 300 and the non-filled variant are deliberate: they are what the design
// specifies (`opsz,wght,FILL,GRAD@20..48,300,0,0`).
//
// Run: npm run gen:icons -w web
