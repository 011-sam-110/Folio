const missing = [];
const entries = [];

for (const [appName, glyph] of Object.entries(MAP)) {
  const file = resolve(SVG_DIR, `${glyph}.svg`);
  if (!existsSync(file)) {
    missing.push(`${appName} -> ${glyph}`);
    continue;
  }
  const svg = readFileSync(file, 'utf8');
  // Every Material Symbol is a single <path d="..."/> on a 0 -960 960 960 viewBox.
  const matches = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (matches.length === 0) {
    missing.push(`${appName} -> ${glyph} (no path data)`);
    continue;
  }
  entries.push([appName, matches.join(' ')]);
}

if (missing.length) {
  console.error('Unresolved Material Symbols:\n  ' + missing.join('\n  '));
  process.exit(1);
}

const body = entries.map(([n, d]) => `  ${JSON.stringify(n)}: ${JSON.stringify(d)},`).join('\n');

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-icons.mjs - do not edit by hand.
// Material Symbols Rounded, weight 300, FILL 0. Run \`npm run gen:icons -w web\`
// after changing the map in that script.
//
// All glyphs share the Material Symbols viewBox, which is NOT the 24x24 box the old
// hand-rolled set used - Icon.tsx sets it, so nothing else needs to know.
export const ICON_VIEWBOX = '0 -960 960 960';

export const ICON_PATHS = {
${body}
} as const;

export type IconName = keyof typeof ICON_PATHS;
`,
  'utf8',
);

console.log(`Wrote ${entries.length} icons to ${OUT}`);
